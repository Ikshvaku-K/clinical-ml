def _last(log: list[dict], key: str):
    vals = [x[key] for x in log if key in x]
    return vals[-1] if vals else None


def render_summ() -> str:
    d = json.loads((config.REPORTS / "summ_data.json").read_text())
    pr = json.loads((config.REPORTS / "summ_pairs.json").read_text())
    ev = json.loads((config.REPORTS / "summ_eval.json").read_text())
    train = {s: json.loads((config.REPORTS / f"summ_train_{s}.json").read_text())
             for s in ("sft", "dpo")}
    test = ev["splits"]["test"]
    r = test["results"]
    lines = [SUMM_START, "", "_Generated by `make report` from `reports/summ_*.json`. Test: "
             f"{test['notes']:,} held-out notes, greedy decoding; 95% CIs from "
             f"{ev['protocol']['n_boot']:,} note-level bootstrap resamples, paired across "
             "models._", "",
             f"**Data:** {d['splits']['sft']:,} SFT, {d['splits']['dpo']:,} DPO, "
             f"{d['splits']['dev']:,} dev and {d['splits']['test']:,} test notes (median "
             f"{d['note_words_median']:.0f} words; reference summaries median "
             f"{d['reference_words']['median']:.0f} words).", "",
             "| Stage | Examples | Wall time | Peak GPU memory | Last logged |",
             "|---|---|---|---|---|"]
    for stage, t in train.items():
        log = t["log_history"]
        if stage == "sft":
            last = f"train loss {_last(log, 'loss'):.3f}"
        else:
            acc = _last(log, "rewards/accuracies")
            mar = _last(log, "rewards/margins")
            last = f"reward accuracy {acc:.2f}, margin {mar:.2f}" if acc is not None else "—"
        lines.append(f"| {stage.upper()} (LoRA r = 16) | {t['examples']:,} | "
                     f"{t['seconds'] / 60:.0f} min | {t['peak_gpu_memory_gb']:.0f} GB | "
                     f"{last} |")
    lines += ["", f"**Preference pairs:** the SFT model wrote {pr['samples']:,} summaries "
              f"({pr['rules']['samples']} per DPO prompt); {pr['usable_samples']:,} were "
              "scorable. phi-4 found every claim supported in "
              f"{pr['sft_sample_faithfulness']['share_fully_supported']:.1%} of them "
              f"(mean faithfulness {pr['sft_sample_faithfulness']['mean']:.3f}). "
              f"{pr['pairs']:,} pairs met the rule ({pr['rules']['pair']}, lengths within "
              f"×{pr['rules']['length_ratio']}; the pre-set {pr['original_rule']} gave "
              f"{pr['pairs_under_original_rule']}); mean gap "
              f"{pr['pair_gap_mean']:.3f}, mean words chosen / rejected "
              f"{pr['words_chosen_vs_rejected'][0]:.0f} / "
              f"{pr['words_chosen_vs_rejected'][1]:.0f}.", "",
              "| Model | " + " | ".join(SUMM_MEASURES.values()) + " |",
              "|---|" + "---|" * len(SUMM_MEASURES)]
