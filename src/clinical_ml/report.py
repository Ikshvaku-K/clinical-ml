"""Render the README results block from reports/*.json, so no number is typed by hand."""

import json
import re

from clinical_ml import config

START, END = "<!-- results:start -->", "<!-- results:end -->"
NAMES = {"logistic_regression": "Logistic regression (L2)",
         "hist_gradient_boosting": "Histogram gradient boosting",
         "xgboost": "XGBoost"}


def _ci(m: dict, digits: int = 3) -> str:
    lo, hi = m["ci95"]
    return f"{m['value']:.{digits}f} ({lo:.{digits}f}–{hi:.{digits}f})"


def render() -> str:
    m1 = json.loads((config.REPORTS / "metrics_m1.json").read_text())
    dq = json.loads((config.REPORTS / "dq.json").read_text())
    cohorts = json.loads((config.REPORTS / "cohorts.json").read_text())
    test = m1["test"]
    lines = [START, "", "_Generated by `make report` from `reports/metrics_m1.json`, "
             "`reports/dq.json` and `reports/cohorts.json`._", ""]

    lines += ["**Test set (held-out patients, scored once).** "
              f"{test['bootstrap']['n_patients']:,} patients / "
              f"{test[next(iter(m1['models']))]['n']:,} encounters, readmission rate "
              f"{test[next(iter(m1['models']))]['prevalence']:.3f}. "
              f"95% CIs from {test['bootstrap']['n_boot']:,} patient-level bootstrap resamples.",
              "",
              "| Model | AUROC | AUPRC | Brier | Grouped 5-fold CV AUROC (train) | MLflow run |",
              "|---|---|---|---|---|---|"]
    for key, info in m1["models"].items():
        t, b = test[key], info["best"]
        lines.append(f"| {NAMES[key]} | {_ci(t['auroc'])} | {_ci(t['auprc'])} | "
                     f"{_ci(t['brier'], 4)} | {b['cv_auroc_mean']:.3f} ± {b['cv_auroc_sd']:.3f} "
                     f"| `{info['run_id'][:8]}` |")
    diff = next(v for k, v in test.items() if k.endswith("_auroc"))
    lines += ["", f"Paired AUROC difference (gradient boosting − logistic): {_ci(diff, 4)}.",
              "These are the raw M1 probabilities; recalibration, conformal sets and the "
              "operating point are in the M2 results below.", ""]

    s = m1["split_sizes"]
    lines += ["**Patient-level split** (no patient in two splits):", "",
              "| Split | Patients | Encounters | 30-day readmission rate |",
              "|---|---|---|---|"]
    lines += [f"| {k} | {v['patients']:,} | {v['encounters']:,} | {v['readmit_rate']:.3f} |"
              for k, v in s.items()]

    lines += ["", "**Cohorts** (same SQL over both OMOP CDMs):", "",
              "| Source | Inpatient visits | Excluded: died / hospice | Excluded: after recorded "
              "death | Eligible | Patients | 30-day readmissions |",
              "|---|---|---|---|---|---|---|"]
    for src, c in cohorts.items():
        lines.append(f"| {src} | {c['index_visits']:,} | {c['excluded_death_or_hospice']:,} | "
                     f"{c['excluded_after_recorded_death']:,} | {c['eligible']:,} | "
                     f"{c['eligible_persons']:,} | {c['readmit_30d']:,} "
                     f"({c['readmit_30d_rate']:.1%}) |")

    lines += ["", "**Data quality.** "
              + ("All error-level checks pass. " if dq["passed"] else "**Some checks FAIL.** ")
              + "Source → OMOP reconciliation:", "",
              "| Check | Source | OMOP |", "|---|---|---|"]
    lines += [f"| {r['check']} | {r['source']:,} | {r['omop']:,} |" for r in dq["reconciliation"]]
    lines += ["", "Standard-concept coverage (rows with a non-zero concept_id):", "",
              "| CDM | Table | Rows | Rows mapped | Distinct source codes |",
              "|---|---|---|---|---|"]
    for sch in dq["schemas"]:
        for t, c in sch["concept_coverage"].items():
            lines.append(f"| {sch['schema']} | {t} | {c['rows']:,} | {c['rows_mapped_pct']}% | "
                         f"{c['distinct_source_codes']:,} |")
    info = [c for sch in dq["schemas"] for c in sch["checks"]
            if c["severity"] == "info" and "coverage" not in c["name"] and c["failing"]]
    for c in info:
        lines.append(f"\nFinding (info): {c['name']}: {c['failing']} of {c['total']:,} rows fail.")
    lines += ["", END]
    return "\n".join(lines)


M2_START, M2_END = "<!-- results-m2:start -->", "<!-- results-m2:end -->"


def render_m2() -> str:
    m2 = json.loads((config.REPORTS / "metrics_m2.json").read_text())
    pr = m2["protocol"]
    lines = [M2_START, "", "_Generated by `make report` from `reports/metrics_m2.json` "
             f"(MLflow run `{m2['run_id'][:8]}`). 95% CIs from {pr['n_boot']:,} patient-level "
             "bootstrap resamples of the test split._", ""]

    lines += ["**Calibration on test** (recalibration chosen by grouped-CV Brier on the "
              "calibration split):", "",
              "| Model | Recalibration | Calibration slope | Intercept (log-odds) | "
              "Observed / expected | ECE | Brier |", "|---|---|---|---|---|---|---|"]
    for key, v in m2["models"].items():
        for stage in ("raw", "recalibrated"):
            if stage == "recalibrated" and v["recalibration"]["selected"] == "none":
                continue
            c = v["calibration_test"][stage]
            label = "none (raw)" if stage == "raw" else v["recalibration"]["selected"]
            lines.append(f"| {NAMES[key]} | {label} | {_ci(c['calibration_slope'])} | "
                         f"{_ci(c['calibration_intercept'])} | "
                         f"{_ci(c['observed_over_expected'])} | {_ci(c['ece'], 4)} | "
                         f"{_ci(c['brier'], 4)} |")

    lines += ["", "![Reliability diagram](reports/figures/reliability.png)", "",
              f"**Operating point: follow up the top {pr['capacity']:.0%} of discharges** "
              "(threshold fixed on the calibration split, then applied to test):", "",
              "| Model | Threshold | Flag rate | Sensitivity | Specificity | PPV | NPV |",
              "|---|---|---|---|---|---|---|"]
    for key, v in m2["models"].items():
        op, t = v["operating_point"], v["operating_point"]["test"]
        lines.append(f"| {NAMES[key]} | {op['threshold']:.3f} | {_ci(t['flag_rate'])} | "
                     f"{_ci(t['sensitivity'])} | {_ci(t['specificity'])} | {_ci(t['ppv'])} | "
                     f"{_ci(t['npv'])} |")
    prev = next(iter(m2["models"].values()))["operating_point"]["test_prevalence"]
    lines += ["", f"Test readmission rate (the PPV of flagging at random): {prev:.3f}.", "",
              "![Decision curve](reports/figures/decision_curve.png)", "",
              "| Model | Net benefit at threshold 0.10 | 0.15 | 0.20 | 0.30 | Beats treat-all "
              "and treat-none over |", "|---|---|---|---|---|---|"]
    for key, v in m2["models"].items():
        nb = v["decision_curve"]["net_benefit"]
        rng = v["decision_curve"]["model_beats_both_defaults_from_to"]
        span = f"{rng[0]:.2f}–{rng[1]:.2f} (of 0.02–0.40 evaluated)" if rng else "—"
        lines.append(f"| {NAMES[key]} | " + " | ".join(
            _ci(nb[f"nb_model@{x}"], 4) for x in (0.1, 0.15, 0.2, 0.3)) + f" | {span} |")
    ta = next(iter(m2["models"].values()))["decision_curve"]["net_benefit"]
    lines += ["| Treat all | " + " | ".join(_ci(ta[f"nb_treat_all@{x}"], 4)
                                            for x in (0.1, 0.15, 0.2, 0.3)) + " | |"]

    lines += ["", f"**Split-conformal prediction sets** (α = {pr['alpha']}, "
              "raw model scores):", "",
              "| Model | Procedure | Coverage | Coverage, readmitted | Coverage, not "
              "readmitted | Sets containing both outcomes | Mean set size |",
              "|---|---|---|---|---|---|---|"]
    names = {"marginal": "marginal", "class_conditional": "class-conditional (Mondrian)",
             "race_conditional": "race-conditional (Mondrian)"}
    for key, v in m2["models"].items():
        for proc, c in v["conformal_test"].items():
            t, ci = c["test"], c["ci95"]
            lines.append(f"| {NAMES[key]} | {names[proc]} | {_ci(ci['coverage'])} | "
                         f"{_ci(ci['coverage_readmitted'])} | {t['coverage_not_readmitted']:.3f}"
                         f" | {_ci(ci['share_both'])} | {t['mean_set_size']:.2f} |")
    primary = m2["primary_model_for_m3"]
    cc = m2["models"][primary]["conformal_test"]["class_conditional"]["test"]["coverage_by_group"]
    lines += ["", f"Class-conditional coverage by race ({NAMES[primary]}): " + ", ".join(
        f"{g} {c['coverage']:.3f} (n={c['n']:,})" for g, c in cc.items()) + ".", "",
        f"Model carried into M3: **{NAMES[primary]}** ({m2['primary_rule']}).", "", M2_END]
    return "\n".join(lines)


def grid_edges(grid: list[dict]) -> list[str]:
    """Hyperparameters whose selected (first) value is the smallest or largest searched."""
    best, edges = grid[0]["params"], []
    for k, v in best.items():
        values = sorted({r["params"][k] for r in grid})
        if len(values) > 1 and v in (values[0], values[-1]):
            edges.append(f"{k}={v} ({'min' if v == values[0] else 'max'})")
    return edges


BENCH_START, BENCH_END = "<!-- results-benchmark:start -->", "<!-- results-benchmark:end -->"


def render_benchmark() -> str:
    b = json.loads((config.REPORTS / "benchmark.json").read_text())
    env, test = b["environment"], b["test"]
    xgb = b["models"]["xgboost"]
    hw = f"{env['cpu_count']} CPU threads" + (f", {env['gpu']}" if env.get("gpu") else "")
    lines = [BENCH_START, "", "_Generated by `make report` from `reports/benchmark.json`. "
             f"All three models trained in one run on {env['platform']} ({hw}); "
             f"XGBoost {env['xgboost_version']} trained on `{xgb['device_used']}`, "
             f"scikit-learn {env['sklearn_version']}. 95% CIs from "
             f"{test['bootstrap']['n_boot']:,} patient-level bootstrap resamples of the "
             f"test split ({test['bootstrap']['n_patients']:,} patients)._", "",
             "| Model | AUROC | AUPRC | Brier | Grouped 5-fold CV AUROC (train) | "
             "Selected hyperparameters | Selection + fit time | MLflow run |",
             "|---|---|---|---|---|---|---|---|"]
    for key, info in b["models"].items():
        t, best = test[key], info["best"]
        params = ", ".join(f"{k}={v}" for k, v in best["params"].items())
        lines.append(f"| {NAMES[key]} | {_ci(t['auroc'])} | {_ci(t['auprc'])} | "
                     f"{_ci(t['brier'], 4)} | {best['cv_auroc_mean']:.3f} ± "
                     f"{best['cv_auroc_sd']:.3f} | {params} | "
                     f"{info['fit_and_select_seconds']:.0f} s | `{info['run_id'][:8]}` |")
    lines += ["", "**Selection surface** (grouped CV on train only; a choice at a grid edge "
              "matters only if the surface is still rising there):", "",
              "| Model | Grid points | Best CV AUROC | 5th best | Fold SD (best) | "
              "Selected value at a grid edge |", "|---|---|---|---|---|---|"]
    for key, info in b["models"].items():
        grid = sorted(info["cv_grid"], key=lambda r: -r["cv_auroc_mean"])
        best = grid[0]
        fifth = f"{grid[4]['cv_auroc_mean']:.4f}" if len(grid) >= 5 else "—"
        lines.append(f"| {NAMES[key]} | {len(grid)} | {best['cv_auroc_mean']:.4f} | "
                     f"{fifth} | {best['cv_auroc_sd']:.4f} | "
                     f"{', '.join(grid_edges(grid)) or 'none'} |")
    base = next(iter(b["models"]))
    lines += ["", f"Paired AUROC differences, each model minus {NAMES[base]} "
              "(same bootstrap resamples):", ""]
    lines += [f"- {NAMES[k.removesuffix(f'_minus_{base}_auroc')]}: {_ci(v, 4)}"
              for k, v in test.items() if k.endswith(f"_minus_{base}_auroc")]
    lines += ["", BENCH_END]
    return "\n".join(lines)


def _replace(text: str, start: str, end: str, block: str) -> str:
    if start in text:
        return re.sub(re.escape(start) + r".*?" + re.escape(end), lambda _: block, text,
                      flags=re.S)
    return text + "\n" + block + "\n"


def update_readme() -> None:
    path = config.ROOT / "README.md"
    text = _replace(path.read_text(), START, END, render())
    if (config.REPORTS / "metrics_m2.json").exists():
        text = _replace(text, M2_START, M2_END, render_m2())
    if (config.REPORTS / "benchmark.json").exists():
        text = _replace(text, BENCH_START, BENCH_END, render_benchmark())
    path.write_text(text)
