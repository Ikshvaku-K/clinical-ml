def _ci(m: dict, digits: int = 3) -> str:
    lo, hi = m["ci95"]
    return f"{m['value']:.{digits}f} ({lo:.{digits}f}–{hi:.{digits}f})"


def render() -> str:
    m1 = json.loads((config.REPORTS / "metrics_m1.json").read_text())
    dq = json.loads((config.REPORTS / "dq.json").read_text())
    cohorts = json.loads((config.REPORTS / "cohorts.json").read_text())
    test = m1["test"]
    lines = [START, "", "_Generated by `make report` from `reports/metrics_m1.json`, "
             "`reports/dq.json` and `reports/cohorts.json`._", ""]

    lines += ["**Test set (held-out patients, scored once).** "
              f"{test['bootstrap']['n_patients']:,} patients / "
              f"{test[next(iter(m1['models']))]['n']:,} encounters, readmission rate "
              f"{test[next(iter(m1['models']))]['prevalence']:.3f}. "
              f"95% CIs from {test['bootstrap']['n_boot']:,} patient-level bootstrap resamples.",
              "",
              "| Model | AUROC | AUPRC | Brier | Grouped 5-fold CV AUROC (train) | MLflow run |",
              "|---|---|---|---|---|---|"]
    for key, info in m1["models"].items():
        t, b = test[key], info["best"]
        lines.append(f"| {NAMES[key]} | {_ci(t['auroc'])} | {_ci(t['auprc'])} | "
                     f"{_ci(t['brier'], 4)} | {b['cv_auroc_mean']:.3f} ± {b['cv_auroc_sd']:.3f} "
                     f"| `{info['run_id'][:8]}` |")
    diff = next(v for k, v in test.items() if k.endswith("_auroc"))
    lines += ["", f"Paired AUROC difference (gradient boosting − logistic): {_ci(diff, 4)}.",
              "These are the raw M1 probabilities; recalibration, conformal sets and the "
              "operating point are in the M2 results below.", ""]

    s = m1["split_sizes"]
    lines += ["**Patient-level split** (no patient in two splits):", "",
              "| Split | Patients | Encounters | 30-day readmission rate |",
              "|---|---|---|---|"]
    lines += [f"| {k} | {v['patients']:,} | {v['encounters']:,} | {v['readmit_rate']:.3f} |"
              for k, v in s.items()]

    lines += ["", "**Cohorts** (same SQL over both OMOP CDMs):", "",
              "| Source | Inpatient visits | Excluded: died / hospice | Excluded: after recorded "
              "death | Eligible | Patients | 30-day readmissions |",
              "|---|---|---|---|---|---|---|"]
    for src, c in cohorts.items():
        lines.append(f"| {src} | {c['index_visits']:,} | {c['excluded_death_or_hospice']:,} | "
                     f"{c['excluded_after_recorded_death']:,} | {c['eligible']:,} | "
                     f"{c['eligible_persons']:,} | {c['readmit_30d']:,} "
                     f"({c['readmit_30d_rate']:.1%}) |")

    lines += ["", "**Data quality.** "
              + ("All error-level checks pass. " if dq["passed"] else "**Some checks FAIL.** ")
              + "Source → OMOP reconciliation:", "",
              "| Check | Source | OMOP |", "|---|---|---|"]
    lines += [f"| {r['check']} | {r['source']:,} | {r['omop']:,} |" for r in dq["reconciliation"]]
    lines += ["", "Standard-concept coverage (rows with a non-zero concept_id):", "",
              "| CDM | Table | Rows | Rows mapped | Distinct source codes |",
              "|---|---|---|---|---|"]
    for sch in dq["schemas"]:
        for t, c in sch["concept_coverage"].items():
            lines.append(f"| {sch['schema']} | {t} | {c['rows']:,} | {c['rows_mapped_pct']}% | "
                         f"{c['distinct_source_codes']:,} |")
    info = [c for sch in dq["schemas"] for c in sch["checks"]
            if c["severity"] == "info" and "coverage" not in c["name"] and c["failing"]]
    for c in info:
        lines.append(f"\nFinding (info): {c['name']}: {c['failing']} of {c['total']:,} rows fail.")
    lines += ["", END]
    return "\n".join(lines)


