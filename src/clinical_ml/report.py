def _source_value(v: str) -> str:
    """OMOP source-value columns are VARCHAR(50), so longer source text arrives cut."""
    return v.strip() + "…" if len(v) >= 50 else v


def _signed(m: dict, digits: int = 3) -> str:
    lo, hi = m["ci95"]
    return f"{m['value']:+.{digits}f} ({lo:+.{digits}f} to {hi:+.{digits}f})"


