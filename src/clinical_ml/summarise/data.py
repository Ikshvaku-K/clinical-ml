"""Phase 2b data: Asclepius summarisation items, split by note.

Each item is one synthetic discharge summary, a summarisation instruction about it, and a
reference summary (generated by GPT-3.5 when the dataset was built). Notes used in the 2a
dev/test questions are excluded, as are references that call the task unanswerable. The
seeded split is by note, so no note is in two splits.
"""

import json

import numpy as np
import pandas as pd

from clinical_ml import config
from clinical_ml.rag import data as rag_data

TASK = "Summarization"
SPLITS = {"sft": 4000, "dpo": 2000, "dev": 100, "test": 300}
OUT = config.DATA / "summarise"

SYSTEM = ("You summarise hospital discharge summaries for clinicians. Use only information "
          "stated in the note, and be concise.")
USER = "Discharge summary:\n{note}\n\nTask: {question}"


def messages(note: str, question: str) -> list[dict]:
    return [{"role": "system", "content": SYSTEM},
            {"role": "user", "content": USER.format(note=note, question=question)}]


def split(df: pd.DataFrame, exclude: set[str], seed: int = config.SEED) -> pd.DataFrame:
    items = df[(df["task"] == TASK) & ~df["note_id"].isin(exclude)
               & ~df["answer"].str.contains(rag_data._UNANSWERABLE)]
    items = items.drop_duplicates("note_id")
    order = np.random.default_rng(seed + 2).permutation(len(items))
    need = sum(SPLITS.values())
    assert len(items) >= need, (len(items), need)
    picked = items.iloc[order[:need]].reset_index(drop=True)
    picked["split"] = np.repeat(list(SPLITS), list(SPLITS.values()))
    return picked[["split", "note_id", "note", "question", "answer"]]


def run() -> dict:
    df = rag_data.load()
    used_2a = set(pd.read_parquet(rag_data.OUT_DIR / "questions.parquet")["note_id"])
    items = split(df, used_2a)
    OUT.mkdir(parents=True, exist_ok=True)
    items.to_parquet(OUT / "items.parquet", index=False)
    words = items.assign(note_words=items["note"].str.split().str.len(),
                         ref_words=items["answer"].str.split().str.len())
    summary = {"task": TASK, "excluded_2a_notes": len(used_2a),
               "splits": {s: int(n) for s, n in items["split"].value_counts().items()},
               "note_words_median": float(words["note_words"].median()),
               "reference_words": {"median": float(words["ref_words"].median()),
                                   "p95": float(words["ref_words"].quantile(0.95))}}
    (config.REPORTS / "summ_data.json").write_text(json.dumps(summary, indent=2))
    return summary
